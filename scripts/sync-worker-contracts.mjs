// Copies the artifact contracts the web app and the local worker must agree on into the worker
// package, which is a separate pnpm package with its own module resolution and cannot import from
// src/.
//
// The two packages already share generated database types the same way (see generate-db-types.mjs).
// A copy that drifts would let the worker write an artifact the admin console cannot parse, so CI
// re-runs this with --check.
//
// Usage: node scripts/sync-worker-contracts.mjs [--check]
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();

const FILES = [
  {
    from: "src/lib/validation/artifacts.ts",
    to: "local-worker/src/contracts/artifacts.ts",
  },
];

const header = (from) =>
  `// Generated by \`pnpm contracts:sync\` from ${from}. Do not edit by hand.\n` +
  `//\n` +
  `// The worker validates every provider result against these schemas before it writes an artifact,\n` +
  `// and the admin console parses the stored artifact with the same definitions.\n\n`;

const check = process.argv.includes("--check");
let stale = false;

for (const file of FILES) {
  const source = readFileSync(path.join(root, file.from), "utf8").replaceAll("\r\n", "\n");
  if (/^\s*import .* from "(\.|@\/)/m.test(source)) {
    throw new Error(`${file.from} imports a local module, so it cannot be copied to the worker`);
  }
  const output = header(file.from) + source;
  const target = path.join(root, file.to);

  if (check) {
    let current = "";
    try {
      current = readFileSync(target, "utf8").replaceAll("\r\n", "\n");
    } catch {
      process.stderr.write(`${file.to} is missing. Run \`pnpm contracts:sync\`.\n`);
      stale = true;
      continue;
    }
    if (current !== output) {
      process.stderr.write(
        `${file.to} is out of date with ${file.from}. Run \`pnpm contracts:sync\`.\n`,
      );
      stale = true;
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, output);
    process.stdout.write(`Wrote ${file.to}\n`);
  }
}

if (check) {
  if (stale) process.exit(1);
  process.stdout.write("Worker contracts are current.\n");
}
