// Generates TypeScript types for the local Supabase database and writes them to the web app and
// the local worker. Runs the Supabase CLI through Node so it works on Windows without a shell.
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const cli = path.join(root, "node_modules", "supabase", "dist", "supabase.js");
const targets = ["src/lib/supabase/database.types.ts", "local-worker/src/db/database.types.ts"];

const result = spawnSync(
  process.execPath,
  [cli, "gen", "types", "typescript", "--local", "--schema", "public"],
  {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
  },
);

if (result.status !== 0 || !result.stdout.includes("export type Database")) {
  process.stderr.write(result.stderr || "supabase gen types produced no output\n");
  process.stderr.write("Is the local stack running? Try `pnpm supabase:start`.\n");
  process.exit(result.status || 1);
}

const header =
  "// Generated by `pnpm db:types` from the local Supabase schema. Do not edit by hand.\n\n";
const body = result.stdout.replace(/\r\n/g, "\n");

for (const target of targets) {
  mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
  writeFileSync(path.join(root, target), header + body);
  process.stdout.write(`Wrote ${target}\n`);
}
