// Generates supabase/seeds/prompts.sql from the Markdown files in prompts/.
//
// The prompt text is authored as Markdown so it is reviewable in a diff, and seeded into
// public.prompt_templates so the admin can version it without a deploy. Keeping the two in sync by
// hand would rot, so the SQL is generated and CI re-runs this with --check.
//
// Usage: node scripts/generate-prompt-seed.mjs [--check]
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(root, "supabase", "seeds", "prompts.sql");

// key -> file. The key is the prompt_templates.key and must match ^[a-z][a-z0-9-]{1,63}$.
const TEMPLATES = [
  {
    key: "editorial-style",
    file: "editorial-style.md",
    notes: "Shared style guide for every stage.",
  },
  { key: "research", file: "research.md", notes: "OpenAI research stage." },
  { key: "draft", file: "draft.md", notes: "Claude drafting stage." },
  { key: "image-brief", file: "image-brief.md", notes: "Gemini image stage, one brief per slot." },
  { key: "audit", file: "audit.md", notes: "OpenAI editorial audit stage." },
  { key: "revise", file: "revise.md", notes: "Claude revision stage." },
];

const PLACEHOLDER = /\{\{([a-zA-Z][a-zA-Z0-9]*)\}\}/g;
const QUOTE = "$prompt$";

/** Placeholders a template expects, as a JSON Schema object the manual and CLI modes can validate. */
function variablesSchema(content) {
  const names = [...new Set([...content.matchAll(PLACEHOLDER)].map((match) => match[1]))].sort();
  return {
    type: "object",
    properties: Object.fromEntries(names.map((name) => [name, { type: "string" }])),
    required: names,
    additionalProperties: false,
  };
}

function sqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

const statements = [];
for (const template of TEMPLATES) {
  const source = path.join(root, "prompts", template.file);
  const content = readFileSync(source, "utf8").replaceAll("\r\n", "\n");
  if (content.includes(QUOTE)) {
    throw new Error(`${template.file} contains the dollar-quote tag ${QUOTE}`);
  }
  if (content.length > 100_000) {
    throw new Error(`${template.file} exceeds the 100000 character column limit`);
  }
  statements.push(
    `insert into public.prompt_templates (site_id, key, version, content, variables_schema, notes, is_active)\n` +
      `select s.id, ${sqlLiteral(template.key)}, 1, ${QUOTE}${content}${QUOTE},\n` +
      `       ${sqlLiteral(JSON.stringify(variablesSchema(content)))}::jsonb,\n` +
      `       ${sqlLiteral(`${template.notes} Seeded from prompts/${template.file}.`)}, true\n` +
      `from public.sites s\n` +
      `where s.slug = 'fintechpulse'\n` +
      `on conflict (site_id, key, version) do nothing;`,
  );
}

// The style guide is referenced by every other prompt, so site_settings points at its active version.
statements.push(
  `update public.site_settings st\n` +
    `set style_guide_template_id = t.id\n` +
    `from public.prompt_templates t\n` +
    `where t.site_id = st.site_id and t.key = 'editorial-style' and t.is_active\n` +
    `  and st.style_guide_template_id is null;`,
);

const header = [
  "-- Generated by `pnpm prompts:seed` from prompts/*.md. Do not edit by hand.",
  "--",
  "-- Version 1 of each prompt template, seeded active. Admin edits create new versions; this seed",
  "-- never overwrites them, so re-running it on an established database is a no-op.",
  "",
].join("\n");

const output = `${header}\n${statements.join("\n\n")}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n");
  } catch {
    process.stderr.write(`${outputPath} is missing. Run \`pnpm prompts:seed\`.\n`);
    process.exit(1);
  }
  if (current !== output) {
    process.stderr.write(
      `${outputPath} is out of date with prompts/. Run \`pnpm prompts:seed\`.\n`,
    );
    process.exit(1);
  }
  process.stdout.write("Prompt seed is current.\n");
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
  process.stdout.write(`Wrote supabase/seeds/prompts.sql (${TEMPLATES.length} templates)\n`);
}
